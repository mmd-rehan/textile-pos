# ──────────────────────────────────────────────────────────────────────────────
# Interactive prompts (only if missing AND --yes is not set AND we have a tty)
# ──────────────────────────────────────────────────────────────────────────────
has_tty() { [ -t 0 ]; }
prompt_value() {
  # $1=var name to set, $2=label, $3=default value
  local __var="$1" __label="$2" __default="$3" __input=""
  if $ASSUME_YES || ! has_tty; then
    eval "$__var=\"\${$__var:-$__default}\""
    return
  fi
  local __current; eval "__current=\"\${$__var-}\""
  if [ -n "$__current" ]; then return; fi
  read -r -p "$__label [$__default]: " __input || true
  eval "$__var=\"\${__input:-$__default}\""
}

prompt_password() {
  # $1=var name, $2=label. Single exit path so xtrace (--debug) is reliably
  # restored, and so secret comparisons are never echoed by `set -x`.
  local __var="$1" __label="$2" __input="" __confirm="" __current=""
  trace_off
  if ! $ASSUME_YES && has_tty; then
    eval "__current=\"\${$__var-}\""
    if [ -z "$__current" ]; then
      while true; do
        read -r -s -p "$__label (min 8 chars, blank = auto-generate): " __input; echo
        if [ -z "$__input" ]; then eval "$__var=\"\""; break; fi
        if [ "${#__input}" -lt 8 ]; then warn "Too short, try again."; continue; fi
        read -r -s -p "Confirm: " __confirm; echo
        if [ "$__input" != "$__confirm" ]; then warn "Did not match, try again."; continue; fi
        eval "$__var=\"$__input\""; break
      done
    fi
  fi
  trace_on
}

