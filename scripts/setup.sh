# ──────────────────────────────────────────────────────────────────────────────
# Secret generation
# ──────────────────────────────────────────────────────────────────────────────
read_env_value() {
  # $1=file $2=key -> echoes the stored value (surrounding quotes stripped), or "".
  # Used to reuse secrets across reruns so DB credentials stay stable.
  local file="$1" key="$2" line=""
  [ -f "$file" ] || { printf '%s' ""; return 0; }
  line="$(grep -E -m1 "^${key}=" "$file" 2>/dev/null || true)"
  line="${line#*=}"
  line="${line%\"}"; line="${line#\"}"
  printf '%s' "$line"
}

gen_secret() {
  # URL-safe alnum (so DATABASE_URL and other strings need no encoding).
  # Run in a subshell with pipefail OFF: `head -c N` closes the pipe after N
  # bytes, so `tr` exits 141 (SIGPIPE). With pipefail on, that 141 became the
  # pipeline status and tripped `set -e`; disabling it makes the status head's 0.
  # `set +x` keeps the generated value out of any --debug trace.
  ( set +o pipefail; set +x; LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c "${1:-24}" )
}

trace_off  # secret generation/reuse must never appear in --debug output
# Reuse secrets a previous run already wrote so re-running setup keeps the same DB
# credentials (the MySQL volume was initialized with them) and the same JWT/session
# secrets. Only generate when truly absent. Generated lengths exceed the documented
# minimums: DB/root >=16, admin >=12, JWT/session strong (48); manual passwords are
# validated in prompt_password.
if [ -z "$DB_PASSWORD" ]; then
  DB_PASSWORD="$(read_env_value "$DOCKER_ENV" MYSQL_PASSWORD)"
  if [ -n "$DB_PASSWORD" ]; then info "Reusing existing DB password from docker/.env."
  else DB_PASSWORD="$(gen_secret 24)"; info "Generated random DB password (24 chars)."; fi
fi
if [ -z "$DB_ROOT_PASSWORD" ]; then
  DB_ROOT_PASSWORD="$(read_env_value "$DOCKER_ENV" MYSQL_ROOT_PASSWORD)"
  if [ -n "$DB_ROOT_PASSWORD" ]; then info "Reusing existing MySQL root password from docker/.env."
  else DB_ROOT_PASSWORD="$(gen_secret 24)"; info "Generated random MySQL root password (24 chars)."; fi
fi
JWT_SECRET="$(read_env_value "$BACKEND_ENV" JWT_SECRET)";         [ -n "$JWT_SECRET" ]     || JWT_SECRET="$(gen_secret 48)"
SESSION_SECRET="$(read_env_value "$BACKEND_ENV" SESSION_SECRET)"; [ -n "$SESSION_SECRET" ] || SESSION_SECRET="$(gen_secret 48)"

