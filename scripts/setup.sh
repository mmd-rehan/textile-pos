#!/usr/bin/env bash
# One-command local setup for textile-pos.
#
# Usage:
#   npm run setup                       # interactive prompts where needed
#   npm run setup -- --yes              # non-interactive; safe defaults + generated secrets
#   npm run setup -- --backend-port 5002 --frontend-port 5174
#
# See README.md for the full list of supported flags.

set -Eeuo pipefail

# Resolve repo root (script lives in <root>/scripts/).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
