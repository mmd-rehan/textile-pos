ok "Prisma client generated"

if ! $SKIP_MIGRATE; then
  (cd "$ROOT_DIR/backend" && npx prisma migrate deploy)
  ok "Migrations applied"
else
  info "Skipping migrations (--skip-migrate)."
fi

