SESSION_SECRET="$(gen_secret 48)"

if [ -z "$ADMIN_PASSWORD" ]; then
  ADMIN_PASSWORD="$(gen_secret 16)"
  ADMIN_PASSWORD_AUTOGENERATED=true
elif [ "${#ADMIN_PASSWORD}" -lt 8 ]; then
  err "Admin password must be at least 8 characters."
  exit 2
fi

# ──────────────────────────────────────────────────────────────────────────────
# Port availability — auto-pick alternates if requested ones are busy
# ──────────────────────────────────────────────────────────────────────────────
port_in_use() {
  local p="$1"
  if command -v lsof >/dev/null 2>&1; then
    lsof -i "tcp:$p" -sTCP:LISTEN >/dev/null 2>&1 && return 0
    return 1
  fi
  # Fallback: try /dev/tcp (bash-builtin). 0 = open (in use).
  ( exec 3<>"/dev/tcp/127.0.0.1/$p" ) >/dev/null 2>&1 && { exec 3>&-; return 0; }
  return 1
}

resolve_port() {
  # $1=label, $2=requested port -> echoes chosen port
  local label="$1" requested="$2" port="$2" tries=0
  while port_in_use "$port"; do
    warn "Port $port is busy. Trying $((port+1))…" >&2
    port=$((port+1)); tries=$((tries+1))
    if [ $tries -ge 50 ]; then
      err "Could not find a free $label port near $requested."
      exit 1
    fi
  done
  if [ "$port" != "$requested" ]; then
    warn "$label port $requested unavailable — using $port instead." >&2
  fi
  echo "$port"
}

