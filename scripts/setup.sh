# ──────────────────────────────────────────────────────────────────────────────
# MySQL credential helpers (verify access; reconcile non-destructively if needed)
# ──────────────────────────────────────────────────────────────────────────────
# Run mysql inside the db container as $1 with password $2 (SQL from stdin).
# The password is passed via MYSQL_PWD — never on the command line — so empty
# passwords work and nothing leaks into the container's process list.
db_mysql() {
  (cd "$ROOT_DIR/docker" && docker compose exec -T -e "MYSQL_PWD=$2" db mysql -u"$1")
}
# True when the given user/password can authenticate to the server at all.
db_can_connect() {
  printf 'SELECT 1;\n' | db_mysql "$1" "$2" >/dev/null 2>&1
}
# True when the given user/password can actually USE the target database ($3).
# This is what the app needs — server-level auth alone isn't enough (the user may
# exist but lack a grant on this database, or the database may not exist yet).
db_can_access_db() {
  printf 'SELECT 1;\n' | (cd "$ROOT_DIR/docker" && docker compose exec -T -e "MYSQL_PWD=$2" db mysql -u"$1" "$3") >/dev/null 2>&1
}
# Escape a value for use inside a single-quoted MySQL string literal.
sql_quote() { printf '%s' "$1" | sed "s/'/''/g"; }

# ──────────────────────────────────────────────────────────────────────────────
# Docker MySQL
# ──────────────────────────────────────────────────────────────────────────────
if ! $SKIP_DOCKER; then
  step "Starting MySQL"
  (cd "$ROOT_DIR/docker" && docker compose up -d)
  ok "docker compose up -d issued"

  step "Waiting for MySQL"
  CID=""; tries=0; HEALTH=""
  while [ $tries -lt 60 ]; do
    CID="$(cd "$ROOT_DIR/docker" && docker compose ps -q db 2>/dev/null || true)"
    if [ -n "$CID" ]; then
      HEALTH="$(docker inspect --format='{{.State.Health.Status}}' "$CID" 2>/dev/null || echo "")"
      if [ "$HEALTH" = "healthy" ]; then ok "MySQL is healthy."; break; fi
      # No usable healthcheck status — fall back to a direct ping in the container.
      if [ -z "$HEALTH" ] || [ "$HEALTH" = "unknown" ] || [ "$HEALTH" = "<no value>" ]; then
        if (cd "$ROOT_DIR/docker" && docker compose exec -T db mysqladmin ping -h localhost --silent) >/dev/null 2>&1; then
          ok "MySQL responded to ping."; HEALTH="healthy"; break
        fi
      fi
    fi
    tries=$((tries+1)); sleep 2
  done
  if [ "${HEALTH:-}" != "healthy" ]; then
    err "MySQL did not become ready in time. Check 'docker compose -f docker/docker-compose.yml logs db'."
    exit 1
  fi

  # `mysqladmin ping` reports "alive" even when credentials are wrong, so verify the
  # configured login actually works before Prisma does (and gives a cryptic error).
  step "Verifying database access"
  trace_off  # this block handles the DB password
  if db_can_access_db "$DB_USER" "$DB_PASSWORD" "$DB_NAME"; then
    ok "Database access verified: '$DB_USER' can use '$DB_NAME'."
  else
    # A pre-existing data volume keeps the credentials it was first initialized with,
    # so a freshly-configured user/password may not exist yet. Try to get in as root
    # and create the database + user (or fix root's password) — without losing data.
    warn "Configured credentials for '$DB_USER' were rejected — reconciling via root (non-destructive)…"
    ROOT_PW=""; ROOT_OK=false
    for __cand in "$DB_ROOT_PASSWORD" "textile_root_pwd" ""; do
      if db_can_connect root "$__cand"; then ROOT_PW="$__cand"; ROOT_OK=true; break; fi
    done
    if $ROOT_OK; then
      __pw="$(sql_quote "$DB_PASSWORD")"
      if $DB_USE_ROOT; then
        printf "CREATE DATABASE IF NOT EXISTS \`%s\`;\nALTER USER 'root'@'%%' IDENTIFIED BY '%s';\nFLUSH PRIVILEGES;\n" \
          "$DB_NAME" "$__pw" | db_mysql root "$ROOT_PW" >/dev/null 2>&1 || true
      else
        printf "CREATE DATABASE IF NOT EXISTS \`%s\`;\nCREATE USER IF NOT EXISTS '%s'@'%%' IDENTIFIED BY '%s';\nALTER USER '%s'@'%%' IDENTIFIED BY '%s';\nGRANT ALL PRIVILEGES ON \`%s\`.* TO '%s'@'%%';\nFLUSH PRIVILEGES;\n" \
          "$DB_NAME" "$DB_USER" "$__pw" "$DB_USER" "$__pw" "$DB_NAME" "$DB_USER" \
          | db_mysql root "$ROOT_PW" >/dev/null 2>&1 || true
      fi
      if db_can_access_db "$DB_USER" "$DB_PASSWORD" "$DB_NAME"; then
        ok "Reconciled existing MySQL: '$DB_USER' can now access '$DB_NAME' (existing data preserved)."
      else
        trace_on
        err "Reached MySQL as root but could not grant '$DB_USER' access to '$DB_NAME'."
        warn "Reset the volume (DELETES its data): docker compose -f docker/docker-compose.yml down -v && npm run setup"
        exit 1
      fi
    else
      trace_on
      err "MySQL is up but no known root password works against the existing data volume."
      warn "The volume was initialized by an earlier run with credentials this setup doesn't have."
      warn "Reset the volume (DELETES its data): docker compose -f docker/docker-compose.yml down -v && npm run setup"
      exit 1
    fi
  fi
  trace_on
else
  info "Skipping docker compose (--skip-docker)."
fi

# ──────────────────────────────────────────────────────────────────────────────
# Install dependencies
# ──────────────────────────────────────────────────────────────────────────────
if ! $SKIP_INSTALL; then
  step "Installing dependencies"
  (cd "$ROOT_DIR" && npm install)
  ok "Dependencies installed"
else
  info "Skipping npm install (--skip-install)."
fi

