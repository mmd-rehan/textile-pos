  ADMIN_PASSWORD="$(read_env_value "$BACKEND_ENV" SEED_ADMIN_PASSWORD)"
  if [ -z "$ADMIN_PASSWORD" ]; then
    ADMIN_PASSWORD="$(gen_secret 16)"
    ADMIN_PASSWORD_AUTOGENERATED=true
  fi
elif [ "${#ADMIN_PASSWORD}" -lt 8 ]; then
  err "Admin password must be at least 8 characters."
  exit 2
fi
trace_on

