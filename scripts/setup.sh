  else
    step "Running seed (standard system data only)"
    info "Running standard system seed. Skipping dev/demo data (pass --with-dev-data to include it)."
    (cd "$ROOT_DIR/backend" && npx prisma db seed)
  fi
  ok "Seed complete"
