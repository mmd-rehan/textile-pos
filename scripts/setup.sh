  (cd "$ROOT_DIR/docker" && docker compose up -d)

  info "Waiting for MySQL to become healthy…"
  CID=""; tries=0
  while [ $tries -lt 60 ]; do
    CID="$(cd "$ROOT_DIR/docker" && docker compose ps -q db 2>/dev/null || true)"
    if [ -n "$CID" ]; then
      HEALTH="$(docker inspect --format='{{.State.Health.Status}}' "$CID" 2>/dev/null || echo "unknown")"
