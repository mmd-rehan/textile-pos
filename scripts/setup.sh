if [ -t 1 ]; then
  C_RESET=$'\033[0m'; C_BOLD=$'\033[1m'
  C_BLUE=$'\033[34m'; C_GREEN=$'\033[32m'; C_YELLOW=$'\033[33m'; C_RED=$'\033[31m'; C_DIM=$'\033[2m'
else
  C_RESET=""; C_BOLD=""; C_BLUE=""; C_GREEN=""; C_YELLOW=""; C_RED=""; C_DIM=""
fi
say()  { printf "%s\n" "$*"; }
info() { printf "${C_BLUE}▸${C_RESET} %s\n" "$*"; }
ok()   { printf "${C_GREEN}✓${C_RESET} %s\n" "$*"; }
warn() { printf "${C_YELLOW}!${C_RESET} %s\n" "$*" >&2; }
err()  { printf "${C_RED}✗${C_RESET} %s\n" "$*" >&2; }

# Current stage label — surfaced by the error handler so failures point at a phase.
STAGE="startup"
step() { STAGE="$*"; printf "\n${C_BOLD}${C_BLUE}== %s ==${C_RESET}\n" "$*"; }

# xtrace toggles for --debug. trace_off is always safe to call; trace_on only
# re-enables tracing when --debug is active. Used to keep secrets out of `set -x`.
trace_off() { { set +x; } 2>/dev/null; }
trace_on()  { if ${DEBUG:-false}; then set -x; fi; }

# Single-shot error handler. Disables the trap and xtrace on the first line so it
# cannot re-fire from inside itself or from subshells (errtrace), reports the
# failing stage exactly once, then exits.
_ERR_HANDLED=false
on_error() {
  trap - ERR
  { set +x; } 2>/dev/null
  if $_ERR_HANDLED; then exit 1; fi
  _ERR_HANDLED=true
  err "Setup failed during '${STAGE}' (line $1)."
  cat <<EOF >&2

Common fixes:
  - Docker not running               → start Docker Desktop, then re-run.
  - Port already used                → setup auto-picks a free port; pass --mysql-port / --backend-port / --frontend-port to force one.
  - MySQL connection failed          → check docker/.env credentials and 'docker compose -f docker/docker-compose.yml ps'.
  - Prisma migration failed          → 'cd backend && npx prisma migrate status' for details.
  - Permission denied on setup.sh    → 'chmod +x scripts/setup.sh' or run 'bash scripts/setup.sh'.
EOF
  exit 1
}
trap 'on_error $LINENO' ERR

