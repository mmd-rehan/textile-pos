# ──────────────────────────────────────────────────────────────────────────────
# Secret generation
# ──────────────────────────────────────────────────────────────────────────────
gen_secret() {
  # 24 alnum chars — URL-safe so DATABASE_URL and other strings don't need encoding.
  LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c "${1:-24}"
}

[ -z "$DB_PASSWORD" ]      && DB_PASSWORD="$(gen_secret 24)"          && info "Generated random DB password."
[ -z "$DB_ROOT_PASSWORD" ] && DB_ROOT_PASSWORD="$(gen_secret 24)"     && info "Generated random MySQL root password."
